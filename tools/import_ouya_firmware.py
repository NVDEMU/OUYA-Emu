#!/usr/bin/env python3
"""Extract OUYA-branded APKs from a user-supplied stock OTA package.

The OTA is not redistributed. Only APKs whose archive paths contain an OUYA
or Cortex identifier are staged; Tegra boot images, kernels, vendor drivers,
and unrelated Android system apps are deliberately ignored.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import zipfile
from pathlib import Path, PurePosixPath

TOKENS = ("ouya", "cortex")
APP_DIRS = ("system/app/", "system/priv-app/")
MAX_APK_SIZE = 512 * 1024 * 1024


def safe_member(name: str) -> bool:
    path = PurePosixPath(name)
    return not path.is_absolute() and ".." not in path.parts


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ota", type=Path, help="stock RC-OUYA OTA ZIP supplied by you")
    parser.add_argument("--out", type=Path,
                        default=Path("vendor/ouya-emu/proprietary/ouya"),
                        help="staging directory (default: vendor/ouya-emu/proprietary/ouya)")
    args = parser.parse_args()

    if not args.ota.is_file():
        parser.error(f"OTA file does not exist: {args.ota}")
    args.out.mkdir(parents=True, exist_ok=True)

    staged: list[dict[str, str | int]] = []
    with zipfile.ZipFile(args.ota) as archive:
        for info in archive.infolist():
            name = info.filename
            lower = name.lower()
            if not safe_member(name) or not name.lower().endswith(".apk"):
                continue
            if not lower.startswith(APP_DIRS):
                continue
            if not any(token in lower for token in TOKENS):
                continue
            if info.file_size > MAX_APK_SIZE:
                print(f"Skipping unusually large APK: {name}", file=sys.stderr)
                continue

            relative = PurePosixPath(name).relative_to("system")
            destination = args.out / "system" / Path(*relative.parts)
            destination.parent.mkdir(parents=True, exist_ok=True)
            with archive.open(info) as source, destination.open("wb") as target:
                target.write(source.read())

            staged.append({
                "ota_path": name,
                "staged_path": destination.as_posix(),
                "size": info.file_size,
            })

    report = {
        "source_ota": args.ota.name,
        "warning": "User-supplied proprietary firmware; not included in this repository.",
        "staged_apks": staged,
    }
    (args.out / "import-report.json").write_text(
        json.dumps(report, indent=2) + "\n", encoding="utf-8"
    )

    makefile = [
        "# Generated by tools/import_ouya_firmware.py; do not commit proprietary APKs.",
        "# Include this file from the OUYA product makefile.",
        "OUYA_IMPORTED_APKS := \\",
    ]
    for index, item in enumerate(staged):
        source = str(item["staged_path"])
        destination = source.split("/system/", 1)[1]
        suffix = " \\" if index < len(staged) - 1 else ""
        makefile.append(f"    {source}:system/{destination}{suffix}")
    if not staged:
        makefile = [
            "# No OUYA/Cortex APKs were found in the supplied OTA.",
            "# Inspect import-report.json and the OTA layout; no files were installed.",
        ]
    else:
        makefile += [
            "",
            "PRODUCT_COPY_FILES += $(OUYA_IMPORTED_APKS)",
        ]
    (args.out / "ouya-imported.mk").write_text("\n".join(makefile) + "\n", encoding="utf-8")

    print(f"Staged {len(staged)} OUYA/Cortex APK(s) in {args.out}")
    print(f"Report: {args.out / 'import-report.json'}")
    if not staged:
        print("No matching APKs found. This OTA may store system files in an image or payload.", file=sys.stderr)
        return 2
    print("Next: inspect the report, then include ouya-imported.mk from device/ouya/ouya_product.mk.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
